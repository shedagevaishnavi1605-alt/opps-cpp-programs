#include <iostream>              // Includes input/output library

using namespace std;             // Allows us to use cout without std::

int main() {                     // Main function: program starts here

    int roll = 101;               // Stores the student's roll number

    char grade = 'A';             // Stores a single character as grade

    float fee = 12500.50;         // Stores the fee amount with decimal value

    cout << "Roll No: " << roll << endl;   // Displays the roll number

    cout << "Grade: " << grade << endl;    // Displays the grade

    cout << "Fee: " << fee << endl;        // Displays the fee amount

    return 0;                     // Ends the program successfully
}